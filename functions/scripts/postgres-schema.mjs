import { DatabaseSync } from 'node:sqlite';
import { prepareSchema } from './sqlite.mjs';

const clock = "to_char(clock_timestamp() AT TIME ZONE 'UTC', 'YYYY-MM-DD\"T\"HH24:MI:SS.MS\"Z\"')";
const sqlite = new DatabaseSync(':memory:');
prepareSchema(sqlite, true);

const tables = sqlite.prepare(`SELECT name, sql FROM sqlite_schema WHERE type = 'table'
  AND name NOT LIKE 'sqlite_%' AND name <> 'schema_migrations' ORDER BY name`).all();
const foreignKeys = [];
const schema = [
  '-- Final AGAP schema derived from the hosted SQLite schema. Historical data migrations are applied only to the source.',
  'CREATE SCHEMA agap;',
  'REVOKE ALL ON SCHEMA agap FROM PUBLIC;',
  'SET search_path = agap, public;',
];

for (const { name, sql } of tables) {
  schema.push(sql
    .replaceAll('INTEGER PRIMARY KEY AUTOINCREMENT', 'BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY')
    .replace(/\bINTEGER\b/g, 'BIGINT')
    .replace(/\bBOOLEAN\b/g, 'BIGINT')
    .replace(/\bDATETIME\b/g, 'TEXT')
    .replace(/\bREAL\b/g, 'DOUBLE PRECISION')
    .replace(/\bBLOB\b/g, 'BYTEA')
    .replace(/\bREFERENCES \w+\(\w+\)(?:\s+ON DELETE (?:CASCADE|SET NULL|RESTRICT|NO ACTION))?/gi, '')
    .replaceAll("strftime('%Y-%m-%dT%H:%M:%fZ','now')", clock)
    .replace(/DEFAULT CURRENT_TIMESTAMP/g, `DEFAULT (${clock})`)
    .replace(/lower\(hex\(randomblob\(4\)\).*?hex\(randomblob\(6\)\)\)/g, 'gen_random_uuid()::text')
    .replace(/\bwindow\b/g, '"window"') + ';');
  for (const key of sqlite.prepare(`PRAGMA foreign_key_list("${name}")`).all()) {
    if (key.seq !== 0) throw new Error(`Composite foreign key needs review: ${name}`);
    foreignKeys.push(`ALTER TABLE ${name} ADD FOREIGN KEY (${key.from}) REFERENCES ${key.table}(${key.to})`
      + ` ON DELETE ${key.on_delete} ON UPDATE ${key.on_update} DEFERRABLE;`);
  }
}
schema.push(...foreignKeys);
for (const { sql } of sqlite.prepare("SELECT sql FROM sqlite_schema WHERE type = 'index' AND sql IS NOT NULL ORDER BY name").all()) {
  schema.push(sql.replace(/\bwindow\b/g, '"window"') + ';');
}
schema.push('CREATE INDEX idx_incidents_sync ON incidents(updated_at, id);');
schema.push('RESET search_path;');
process.stdout.write(schema.join('\n\n') + '\n');
sqlite.close();
