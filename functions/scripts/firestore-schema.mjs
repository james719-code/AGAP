import { DatabaseSync } from 'node:sqlite';
import { prepareSchema } from './sqlite.mjs';

const db = new DatabaseSync(':memory:');
prepareSchema(db, true);
function fromDefault(value) {
  if (value == null || value === 'NULL') return null;
  if (value.startsWith('strftime(') || value === 'CURRENT_TIMESTAMP') return { generated: 'now' };
  if (value.includes('randomblob(')) return { generated: 'uuid' };
  if (value.startsWith("'")) return value.slice(1, -1).replaceAll("''", "'");
  if (Number.isFinite(Number(value))) return Number(value);
  throw new Error(`Unknown column default: ${value}`);
}

console.log('// Generated by scripts/firestore-schema.mjs. Update along with the PostgreSQL migration.');
console.log('export const schema = {');
for (const { name, sql } of db.prepare("SELECT name, sql FROM sqlite_schema WHERE type='table' AND name NOT LIKE 'sqlite_%' AND name <> 'schema_migrations' ORDER BY name").all()) {
  const columns = db.prepare(`PRAGMA table_info("${name}")`).all();
  const keys = columns.filter((column) => column.pk).sort((a, b) => a.pk - b.pk).map((column) => column.name);
  const generatedId = /id\s+INTEGER PRIMARY KEY AUTOINCREMENT/i.test(sql);
  const defaults = Object.fromEntries(columns.map((column) => [column.name, fromDefault(column.dflt_value)]));
  const required = columns.filter((column) => column.notnull || column.pk).map((column) => column.name);
  const references = db.prepare(`PRAGMA foreign_key_list("${name}")`).all().map((key) => [key.from, key.table, key.to, key.on_delete]);
  const unique = {};
  for (const index of db.prepare(`PRAGMA index_list("${name}")`).all().filter((item) => item.unique)) {
    const fields = db.prepare(`PRAGMA index_info("${index.name}")`).all().map((item) => item.name);
    if (fields.join(',') !== keys.join(',')) unique[fields.join(',')] = index.partial ? index.name : true;
  }
  console.log(`  ${name}: ${JSON.stringify({ keys, generatedId, defaults, required, references, unique })},`);
}
console.log('};');
db.close();
