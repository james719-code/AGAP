/**
 * Repository responsible for incident messaging across:
 *
 * 1. Internet / REST
 * 2. Nearby Connections P2P_CLUSTER
 * 3. Native BLE/GATT fallback
 *
 * Server-defined predefined messages are the only operational replies
 * generated by the Android client.
 *
 * When Internet is available:
 *      Android -> REST -> AGAP Backend
 *
 * When Internet is unavailable:
 *      Android -> compact response packet
 *              -> Nearby Connections
 *              -> BLE/GATT fallback
 *
 * The selected predefined response is also kept in the local sync queue
 * until the originating device can upload it to the authoritative backend.
 */
@Singleton
class IncidentMessagingRepository @Inject constructor(
    private val incidentApiService: IncidentApiService,
    private val messageDao: MessageDao,
    private val predefinedMessageDao: PredefinedMessageDao,
    private val predefinedMessageRepository: PredefinedMessageRepository,
    private val pendingSyncDao: PendingSyncDao,
    private val incidentDao: IncidentDao,
    private val bleMeshManager: BleMeshManager,
    private val serverConfigManager: ServerConfigManager
) {

    private val json = Json {
        ignoreUnknownKeys = true
        encodeDefaults = true
    }

    // -------------------------------------------------------------------------
    // OBSERVATION
    // -------------------------------------------------------------------------

    /**
     * Observe the locally cached conversation for a specific incident.
     *
     * incidentKey may be:
     * - backend numeric incident ID
     * - local/offline UUID incident ID
     */
    fun observeMessages(
        incidentKey: String
    ): Flow<List<IncidentMessageEntity>> {
        return messageDao.getMessagesForIncident(incidentKey).map { list ->
            deduplicateMessages(list)
        }
    }

    /**
     * Observe all active server-controlled fixed reply choices.
     *
     * This comes from Room so it remains available offline after
     * being downloaded from the backend.
     */
    fun observeReplyChoices(): Flow<List<PredefinedMessageEntity>> {
        return predefinedMessageDao.getActiveReplyMessagesFlow()
    }

    // -------------------------------------------------------------------------
    // SERVER CATALOG
    // -------------------------------------------------------------------------

    /**
     * Synchronizes predefined operational replies from the backend.
     *
     * FORCE_BLE_MESH intentionally blocks Internet access because the user
     * explicitly selected an offline-only communication policy.
     *
     * Previously downloaded Room entries remain available.
     */
    suspend fun refreshCatalog(): Result<*> {
        if (
            serverConfigManager.getTransmissionMode() ==
            TransmissionMode.FORCE_BLE_MESH
        ) {
            return Result.Success(Unit)
        }

        return predefinedMessageRepository.syncCatalog()
    }

    // -------------------------------------------------------------------------
    // MESSAGE SYNCHRONIZATION
    // -------------------------------------------------------------------------

    /**
     * Download messages belonging to an incident from the backend.
     *
     * Offline/local incidents without a numeric server ID simply return zero.
     */
    suspend fun refreshOnlineMessages(
        incident: IncidentEntity
    ): Result<Int> {

        val serverId = incident.incidentId.toLongOrNull()
            ?: return Result.Success(0)

        if (
            serverConfigManager.getTransmissionMode() ==
            TransmissionMode.FORCE_BLE_MESH
        ) {
            return Result.Success(0)
        }

        return try {
            val response = incidentApiService.listMessages(serverId)

            if (response.isSuccessful) {
                val body = response.body().orEmpty()

                val catalogById = predefinedMessageDao
                    .getAllMessages()
                    .associateBy { it.id.toLong() }

                val mapped = body.map { dto ->
                    val predefined = dto.predefinedMessageId
                        ?.let { catalogById[it] }

                    dto.toEntity(
                        localIncidentKey = incident.incidentId,
                        catalog = predefined
                    )
                }

                if (mapped.isNotEmpty()) {
                    val existingLocal = messageDao.getMessagesForIncidentList(incident.incidentId)
                    val toDelete = mutableListOf<String>()
                    val toInsert = mapped.map { serverMsg ->
                        var updatedMsg = serverMsg
                        val matchingLocal = existingLocal.find { local ->
                            local.id != serverMsg.id && isDuplicateMessage(local, serverMsg)
                        }
                        if (matchingLocal != null) {
                            toDelete.add(matchingLocal.id)
                            if (matchingLocal.channel.contains("MESH", ignoreCase = true) ||
                                matchingLocal.channel.contains("BLE", ignoreCase = true)
                            ) {
                                updatedMsg = serverMsg.copy(channel = "MESH")
                            }
                        }
                        updatedMsg
                    }

                    for (delId in toDelete) {
                        messageDao.deleteMessage(delId)
                    }

                    messageDao.insertMessages(toInsert)
                }

                Result.Success(mapped.size)
            } else {
                Result.Error(UserMessageResolver.http("refresh incident replies", response.code()))
            }
        } catch (cancel: CancellationException) {
            throw cancel
        } catch (e: Exception) {
            Result.Error(UserMessageResolver.network("Refresh incident replies", e))
        }
    }

    // -------------------------------------------------------------------------
    // SEND PREDEFINED REPLY
    // -------------------------------------------------------------------------

    /**
     * Sends a server-defined fixed response.
     *
     * Behavior:
     *
     * AUTO / HYBRID:
     *      Internet first.
     *      Nearby/BLE relay when Internet send fails.
     *
     * FORCE_BLE_MESH:
     *      No Internet request.
     *      Nearby preferred, BLE fallback.
     *
     * FORCE_INTERNET:
     *      Internet only.
     *      If unavailable, preserve in cloud sync queue.
     */
    suspend fun sendPredefinedReply(
        incident: IncidentEntity,
        choice: PredefinedMessageEntity,
        senderRole: String
    ): Result<String> {

        // ---------------------------------------------------------------------
        // Validate server-defined choice
        // ---------------------------------------------------------------------

        if (!choice.isActive) {
            return Result.Error(
                "This predefined reply is no longer active"
            )
        }

        if (choice.messageType !in ALLOWED_REPLY_TYPES) {
            return Result.Error(
                "This reply is not available for this incident. Choose another reply."
            )
        }

        if (choice.protocolCode !in 1..255) {
            return Result.Error(
                "Reply protocol code must be between 1 and 255"
            )
        }

        val mode = serverConfigManager.getTransmissionMode()

        // ---------------------------------------------------------------------
        // Optimistic local message
        // ---------------------------------------------------------------------

        val localId = "local:${UUID.randomUUID()}"

        val optimisticMessage = IncidentMessageEntity(
            id = localId,
            incidentId = incident.incidentId,
            senderName = "You",
            senderRole = senderRole,
            messageContent = choice.messageText,
            messageType = choice.messageType,
            createdAt = System.currentTimeMillis(),
            predefinedMessageId = choice.id.toLong(),
            predefinedCode = choice.code,
            protocolCode = choice.protocolCode,
            channel = when (mode) {
                TransmissionMode.FORCE_BLE_MESH -> "MESH"
                TransmissionMode.FORCE_INTERNET -> "ONLINE"
                else -> "LOCAL"
            },
            deliveryState = "SENDING"
        )

        messageDao.insertMessage(optimisticMessage)

        // ---------------------------------------------------------------------
        // Internet-first path
        // ---------------------------------------------------------------------

        if (mode != TransmissionMode.FORCE_BLE_MESH) {
            val serverId = incident.incidentId.toLongOrNull()

            if (serverId != null) {
                when (
                    val onlineResult = sendOnline(
                        incidentId = serverId,
                        predefinedMessageId = choice.id.toLong(),
                        localIncidentKey = incident.incidentId
                    )
                ) {
                    is Result.Success -> {
                        messageDao.deleteMessage(localId)
                        messageDao.insertMessage(onlineResult.data)

                        return Result.Success(
                            "Reply sent through Internet"
                        )
                    }

                    is Result.Error -> {
                        // Continue into durable queue / relay path.
                    }

                    Result.Loading -> {
                        // Continue into durable queue / relay path.
                    }
                }
            }
        }

        // ---------------------------------------------------------------------
        // Durable cloud synchronization record
        // ---------------------------------------------------------------------

        queueForCloud(
            incident = incident,
            choice = choice,
            localMessageId = localId,
            senderRole = senderRole
        )

        // ---------------------------------------------------------------------
        // Internet-only policy
        // ---------------------------------------------------------------------

        if (mode == TransmissionMode.FORCE_INTERNET) {
            messageDao.updateDeliveryState(
                localId,
                "QUEUED_FOR_INTERNET",
                "ONLINE"
            )

            return Result.Success(
                "Reply queued until Internet is available"
            )
        }

        // ---------------------------------------------------------------------
        // Nearby / BLE relay
        // ---------------------------------------------------------------------

        val packetToken = incident.packetHash.trim()

        if (packetToken.isNotEmpty()) {
            val queued = bleMeshManager.queuePredefinedResponse(
                incidentIdentifier = packetToken,
                messageType = choice.messageType,
                protocolCode = choice.protocolCode
            )

            if (queued) {
                messageDao.updateDeliveryState(
                    localId,
                    "RELAY_QUEUED",
                    "MESH"
                )

                return Result.Success(
                    if (mode == TransmissionMode.FORCE_BLE_MESH) {
                        "Reply queued for Nearby/BLE relay"
                    } else {
                        "Internet unavailable • reply queued for nearby relay"
                    }
                )
            }
        }

        // ---------------------------------------------------------------------
        // No usable mesh packet identifier
        // ---------------------------------------------------------------------

        messageDao.updateDeliveryState(
            localId,
            "QUEUED_FOR_INTERNET",
            "LOCAL"
        )

        return Result.Success(
            "Reply saved locally; no relay token is available yet"
        )
    }

    // -------------------------------------------------------------------------
    // OFFLINE -> CLOUD SYNCHRONIZATION
    // -------------------------------------------------------------------------

    /**
     * Upload locally-created responses after Internet returns.
     *
     * Relayed third-party responses are deliberately excluded because the
     * compact v2 relay packet does not contain cryptographically authenticated
     * sender identity.
     */
    suspend fun flushPendingReplies(
        limit: Int = DEFAULT_PENDING_FLUSH_LIMIT
    ): Int {

        val boundedLimit = limit.coerceIn(
            1,
            MAX_PENDING_FLUSH_LIMIT
        )

        val items = pendingSyncDao.getPendingSyncItemsByType(
            syncType = SYNC_TYPE,
            status = "PENDING",
            limit = boundedLimit
        )

        var uploaded = 0

        for (item in items) {

            val payload = try {
                json.decodeFromString(
                    PendingIncidentReplyPayload.serializer(),
                    item.payloadJson
                )
            } catch (_: Exception) {
                // Payload itself is corrupt / cannot be decoded.
                pendingSyncDao.updateSyncStatus(
                    item.syncId,
                    "FAILED"
                )
                continue
            }

            val serverId = resolveServerIncidentId(payload)

            // Offline-created incident may not yet exist on the server.
            if (serverId == null) {
                continue
            }

            when (
                val result = sendOnline(
                    incidentId = serverId,
                    predefinedMessageId = payload.predefinedMessageId,
                    localIncidentKey = payload.incidentKey
                )
            ) {
                is Result.Success -> {

                    messageDao.deleteMessage(
                        payload.localMessageId
                    )

                    messageDao.insertMessage(
                        result.data
                    )

                    pendingSyncDao.deleteSyncItem(
                        item.syncId
                    )

                    uploaded++
                }

                is Result.Error -> {

                    /**
                     * Do NOT permanently discard an emergency reply because
                     * Internet/backend connectivity is temporarily unavailable.
                     *
                     * WorkManager controls actual retry pacing.
                     */
                    pendingSyncDao.updateSyncStatus(
                        item.syncId,
                        "PENDING"
                    )

                    messageDao.updateDeliveryState(
                        payload.localMessageId,
                        "QUEUED_FOR_INTERNET",
                        "LOCAL"
                    )
                }

                Result.Loading -> Unit
            }
        }

        return uploaded
    }

    // -------------------------------------------------------------------------
    // RESOLVE SERVER INCIDENT
    // -------------------------------------------------------------------------

    private suspend fun resolveServerIncidentId(
        payload: PendingIncidentReplyPayload
    ): Long? {

        // Already a server incident.
        payload.incidentKey
            .toLongOrNull()
            ?.let { return it }

        // Offline / relayed incident:
        // resolve the eventual server ID through its packet hash.
        val packetHash = payload.packetHash
            ?.trim()
            ?.takeIf { it.isNotEmpty() }
            ?: return null

        return incidentDao
            .getServerIncidentByPacketHash(packetHash)
            ?.incidentId
            ?.toLongOrNull()
    }

    // -------------------------------------------------------------------------
    // SEND VIA REST
    // -------------------------------------------------------------------------

    private suspend fun sendOnline(
        incidentId: Long,
        predefinedMessageId: Long,
        localIncidentKey: String
    ): Result<IncidentMessageEntity> {

        return try {
            val response = incidentApiService.sendMessage(
                incidentId = incidentId,
                request = SendMessageRequestDto(
                    predefinedMessageId = predefinedMessageId,
                    channel = "ONLINE"
                )
            )

            if (response.isSuccessful) {
                val dto = response.body()

                if (dto == null) {
                    return Result.Error(
                        "Server returned an empty reply"
                    )
                }

                val catalog = dto.predefinedCode
                    ?.trim()
                    ?.takeIf { it.isNotEmpty() }
                    ?.let { code ->
                        predefinedMessageDao.getMessageByCode(code)
                    }

                Result.Success(
                    dto.toEntity(
                        localIncidentKey = localIncidentKey,
                        catalog = catalog
                    )
                )
            } else {
                Result.Error(UserMessageResolver.http("send the reply", response.code()))
            }
        } catch (cancel: CancellationException) {
            throw cancel
        } catch (e: Exception) {
            Result.Error(UserMessageResolver.network("Send the reply", e))
        }
    }

    // -------------------------------------------------------------------------
    // DURABLE PENDING CLOUD RECORD
    // -------------------------------------------------------------------------

    private suspend fun queueForCloud(
        incident: IncidentEntity,
        choice: PredefinedMessageEntity,
        localMessageId: String,
        senderRole: String
    ) {

        val packetHash = incident.packetHash
            .trim()
            .takeIf { it.isNotEmpty() }

        val payload = PendingIncidentReplyPayload(
            incidentKey = incident.incidentId,
            packetHash = packetHash,
            predefinedMessageId = choice.id.toLong(),
            localMessageId = localMessageId,
            senderRole = senderRole
        )

        pendingSyncDao.insertSyncItem(
            PendingSyncEntity(
                syncType = SYNC_TYPE,
                payloadJson = json.encodeToString(
                    PendingIncidentReplyPayload.serializer(),
                    payload
                ),
                reportUuid = packetHash
            )
        )
    }

    // -------------------------------------------------------------------------
    // DTO -> ROOM
    // -------------------------------------------------------------------------

    /**
     * Converts the current backend message format into the local Room model.
     *
     * The DTO itself is backward-compatible with old/new server field names.
     */
    private fun IncidentMessageDto.toEntity(
        localIncidentKey: String,
        catalog: PredefinedMessageEntity? = null
    ): IncidentMessageEntity {

        val content = messageEn
            ?.trim()
            ?.takeIf { it.isNotEmpty() }
            ?: customMessage
                ?.trim()
                ?.takeIf { it.isNotEmpty() }
            ?: messageContent
                .trim()
                .takeIf { it.isNotEmpty() }
            ?: predefinedCode
                ?.trim()
                ?.takeIf { it.isNotEmpty() }
            ?: "Operational update"

        val resolvedSenderName = senderName
            .trim()
            .takeIf { it.isNotEmpty() }
            ?: "AGAP Command"

        val resolvedMessageType = catalog?.messageType
            ?: messageType
                .trim()
                .takeIf { it.isNotEmpty() }
            ?: if (predefinedMessageId != null) {
                "STATUS"
            } else {
                "CHAT"
            }

        val resolvedCreatedAt = parseServerTime(
            sentAt?.takeIf { it.isNotBlank() }
                ?: createdAt.takeIf { it.isNotBlank() }
        )

        return IncidentMessageEntity(
            id = "server:$id",
            incidentId = localIncidentKey,

            senderId = senderId,

            senderName = resolvedSenderName,

            senderRole = senderRole
                .trim()
                .takeIf { it.isNotEmpty() }
                ?: "COMMAND",

            messageContent = content,

            messageType = resolvedMessageType,

            createdAt = resolvedCreatedAt,

            predefinedMessageId = predefinedMessageId,

            predefinedCode = predefinedCode,

            protocolCode = catalog?.protocolCode ?: 0,

            channel = channel.ifBlank { "ONLINE" },

            deliveryState = "DELIVERED"
        )
    }

    // -------------------------------------------------------------------------
    // ANDROID API 24 SAFE SERVER TIME PARSER
    // -------------------------------------------------------------------------

    /**
     * Parses common ISO-8601 / RFC-3339 server timestamps WITHOUT java.time.
     *
     * This deliberately avoids:
     *
     *     Instant.parse(...)
     *     Instant.toEpochMilli()
     *
     * because java.time.Instant is natively available only from Android API 26
     * unless core-library desugaring is enabled.
     *
     * AGAP currently supports minSdk 24, therefore this implementation uses
     * java.text.SimpleDateFormat which is safe for those devices.
     *
     * Supported examples:
     *
     * 2026-08-10T03:32:24Z
     * 2026-08-10T03:32:24.834Z
     * 2026-08-10T03:32:24+08:00
     * 2026-08-10T03:32:24.834+08:00
     */
    private fun parseServerTime(
        raw: String?
    ): Long {

        if (raw.isNullOrBlank()) {
            return System.currentTimeMillis()
        }

        val input = normalizeIsoTimestamp(
            raw.trim()
        )

        for (pattern in SERVER_TIME_PATTERNS) {
            try {
                val formatter = SimpleDateFormat(
                    pattern,
                    Locale.US
                ).apply {
                    isLenient = false
                    timeZone = TimeZone.getTimeZone("UTC")
                }

                val parsed = formatter.parse(input)

                if (parsed != null) {
                    return parsed.time
                }
            } catch (_: ParseException) {
                // Try the next format.
            } catch (_: IllegalArgumentException) {
                // Unsupported/bad format on a vendor implementation.
            }
        }

        // Timestamp parsing must never crash the incident screen.
        return System.currentTimeMillis()
    }

    /**
     * Converts:
     *
     * +08:00
     *
     * to:
     *
     * +0800
     *
     * so the legacy RFC-822 'Z' timezone parser can understand it reliably
     * across older Android versions.
     */
    private fun normalizeIsoTimestamp(
        value: String
    ): String {

        if (value.endsWith("Z", ignoreCase = true)) {
            return value.dropLast(1) + "+0000"
        }

        val timezoneRegex = Regex(
            "([+-]\\d{2}):(\\d{2})$"
        )

        return value.replace(
            timezoneRegex,
            "$1$2"
        )
    }

    companion object {

        const val SYNC_TYPE =
            "INCIDENT_PREDEFINED_REPLY"

        private const val DEFAULT_PENDING_FLUSH_LIMIT =
            50

        private const val MAX_PENDING_FLUSH_LIMIT =
            100

        private val ALLOWED_REPLY_TYPES =
            setOf(
                "ACK",
                "STATUS"
            )

        /**
         * Ordered from most precise/common to more relaxed variants.
         *
         * Z = RFC-822 timezone after normalizeIsoTimestamp().
         */
        private val SERVER_TIME_PATTERNS =
            listOf(
                "yyyy-MM-dd'T'HH:mm:ss.SSSSSSZ",
                "yyyy-MM-dd'T'HH:mm:ss.SSSSSZ",
                "yyyy-MM-dd'T'HH:mm:ss.SSSSZ",
                "yyyy-MM-dd'T'HH:mm:ss.SSSZ",
                "yyyy-MM-dd'T'HH:mm:ss.SSZ",
                "yyyy-MM-dd'T'HH:mm:ss.SZ",
                "yyyy-MM-dd'T'HH:mm:ssZ",
                "yyyy-MM-dd HH:mm:ss.SSSZ",
                "yyyy-MM-dd HH:mm:ssZ",
                "yyyy-MM-dd'T'HH:mm:ss.SSS",
                "yyyy-MM-dd'T'HH:mm:ss",
                "yyyy-MM-dd HH:mm:ss.SSS",
                "yyyy-MM-dd HH:mm:ss"
            )
    }
}

internal fun IncidentEntity.messageServerId(): Long? =
    serverIncidentId ?: incidentId.toLongOrNull()

internal fun deduplicateMessages(
    messages: List<IncidentMessageEntity>
): List<IncidentMessageEntity> {
    if (messages.size <= 1) return messages

    val result = mutableListOf<IncidentMessageEntity>()

    for (msg in messages) {
        val existingIndex = result.indexOfFirst { existing ->
            isDuplicateMessage(existing, msg)
        }

        if (existingIndex == -1) {
            result.add(msg)
        } else {
            val existing = result[existingIndex]
            val isMeshOrigin = existing.channel.contains("MESH", ignoreCase = true) ||
                existing.channel.contains("BLE", ignoreCase = true) ||
                msg.channel.contains("MESH", ignoreCase = true) ||
                msg.channel.contains("BLE", ignoreCase = true)

            val mergedChannel = if (isMeshOrigin) "MESH" else (if (msg.id.startsWith("server:")) msg.channel else existing.channel)

            val preferredMsg = if (msg.id.startsWith("server:") && !existing.id.startsWith("server:")) {
                msg.copy(channel = mergedChannel)
            } else {
                existing.copy(channel = mergedChannel)
            }

            result[existingIndex] = preferredMsg
        }
    }

    return result
}

internal fun isDuplicateMessage(
    a: IncidentMessageEntity,
    b: IncidentMessageEntity
): Boolean {
    if (a.id == b.id) return true

    if (a.isSystem != b.isSystem) return false
    if (a.isSystem && b.isSystem) {
        return a.messageContent == b.messageContent && Math.abs(a.createdAt - b.createdAt) < 60_000L
    }

    if (a.incidentId != b.incidentId) return false

    val predefinedMatch = (a.predefinedMessageId != null && a.predefinedMessageId == b.predefinedMessageId) ||
        (a.protocolCode != 0 && a.protocolCode == b.protocolCode) ||
        (!a.predefinedCode.isNullOrBlank() && a.predefinedCode == b.predefinedCode)

    if (predefinedMatch) {
        val roleMatch = a.senderRole.equals(b.senderRole, ignoreCase = true)
        val timeClose = Math.abs(a.createdAt - b.createdAt) < 15 * 60 * 1000L
        if (roleMatch && timeClose) return true
    }

    if (a.messageContent.equals(b.messageContent, ignoreCase = true) &&
        a.senderRole.equals(b.senderRole, ignoreCase = true) &&
        Math.abs(a.createdAt - b.createdAt) < 2 * 60 * 1000L
    ) {
        return true
    }

    return false
}
